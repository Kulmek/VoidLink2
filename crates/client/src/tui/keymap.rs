//! Раскладка: русские клавиши ЙЦУКЕН → латиница QWERTY.
//!
//! Терминал присылает символ, а не скан-код, поэтому при включённой русской
//! раскладке хоткей `q` приходит как `й`. [`latin`] переводит символ обратно в
//! ту латинскую клавишу, что стоит на том же месте клавиатуры.
#![allow(dead_code)] // подключается при интеграции

/// Пары (кириллица, латиница) для строчных символов на одной физической клавише.
const LOWER: &[(char, char)] = &[
    ('й', 'q'), ('ц', 'w'), ('у', 'e'), ('к', 'r'), ('е', 't'), ('н', 'y'),
    ('г', 'u'), ('ш', 'i'), ('щ', 'o'), ('з', 'p'), ('х', '['), ('ъ', ']'),
    ('ф', 'a'), ('ы', 's'), ('в', 'd'), ('а', 'f'), ('п', 'g'), ('р', 'h'),
    ('о', 'j'), ('л', 'k'), ('д', 'l'), ('ж', ';'), ('э', '\''),
    ('я', 'z'), ('ч', 'x'), ('с', 'c'), ('м', 'v'), ('и', 'b'), ('т', 'n'),
    ('ь', 'm'), ('б', ','), ('ю', '.'), ('ё', '`'),
];

/// Пары для заглавных (с Shift): буквы → заглавная латиница, знаки → их
/// шифт-вариант на QWERTY (`Х` → `{`, `Ж` → `:` и т.д.).
const UPPER: &[(char, char)] = &[
    ('Й', 'Q'), ('Ц', 'W'), ('У', 'E'), ('К', 'R'), ('Е', 'T'), ('Н', 'Y'),
    ('Г', 'U'), ('Ш', 'I'), ('Щ', 'O'), ('З', 'P'), ('Х', '{'), ('Ъ', '}'),
    ('Ф', 'A'), ('Ы', 'S'), ('В', 'D'), ('А', 'F'), ('П', 'G'), ('Р', 'H'),
    ('О', 'J'), ('Л', 'K'), ('Д', 'L'), ('Ж', ':'), ('Э', '"'),
    ('Я', 'Z'), ('Ч', 'X'), ('С', 'C'), ('М', 'V'), ('И', 'B'), ('Т', 'N'),
    ('Ь', 'M'), ('Б', '<'), ('Ю', '>'), ('Ё', '~'),
];

/// Возвращает латинский символ той же клавиши; прочие символы — без изменений.
pub fn latin(c: char) -> char {
    if c.is_ascii() {
        return c;
    }
    LOWER
        .iter()
        .chain(UPPER)
        .find(|(ru, _)| *ru == c)
        .map_or(c, |&(_, en)| en)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn letters_both_cases() {
        assert_eq!(latin('й'), 'q');
        assert_eq!(latin('Й'), 'Q');
        assert_eq!(latin('ф'), 'a');
        assert_eq!(latin('я'), 'z');
        assert_eq!(latin('ь'), 'm');
        assert_eq!(latin('Т'), 'N');
    }

    #[test]
    fn punctuation_keys() {
        assert_eq!(latin('х'), '[');
        assert_eq!(latin('ъ'), ']');
        assert_eq!(latin('ж'), ';');
        assert_eq!(latin('э'), '\'');
        assert_eq!(latin('б'), ',');
        assert_eq!(latin('ю'), '.');
        assert_eq!(latin('ё'), '`');
        assert_eq!(latin('Ж'), ':');
        assert_eq!(latin('Ё'), '~');
    }

    #[test]
    fn passthrough() {
        for c in ['q', 'Q', '1', ' ', '?', '€', '中'] {
            assert_eq!(latin(c), c);
        }
    }

    #[test]
    fn full_rows() {
        let ru: String = "йцукенгшщзхъфывапролджэячсмитьбюё".chars().map(latin).collect();
        assert_eq!(ru, "qwertyuiop[]asdfghjkl;'zxcvbnm,.`");
        let up: String = "ЙЦУКЕНГШЩЗФЫВАПРОЛДЯЧСМИТЬ".chars().map(latin).collect();
        assert_eq!(up, "QWERTYUIOPASDFGHJKLZXCVBNM");
    }
}
